"""Extract public district IDs and official card links only. Requires pdfplumber."""
import argparse
from html.parser import HTMLParser
from io import BytesIO
import json
from pathlib import Path
import re
from urllib.parse import urljoin, urlsplit
from urllib.request import urlopen

import pdfplumber

ZH = "https://www.zh.ch/content/dam/zhweb/bilder-dokumente/themen/umwelt-tiere/tiere/fischerei-und-jagd/fischerei/fischereireviere/Fischereirevierverzeichnis_20261030.pdf"
SG = "https://www.sg.ch/umwelt-natur/jagd-fischerei/fischerei/pachten-von-gewaessern/liste-pachtgewaesser.html"
AG = "https://www.ag.ch/de/themen/landwirtschaft-tiere/wild-wassertiere/fischerei/neuverpachtung"
OUTPUT = Path(__file__).resolve().parents[1] / "map-rights-registers.js"


class CardLinks(HTMLParser):
    def __init__(self, source):
        super().__init__()
        self.source = source
        self.href = None
        self.words = []
        self.cards = {}

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            self.href = urljoin(self.source, dict(attrs).get("href", ""))
            self.words = []

    def handle_data(self, text):
        if self.href:
            self.words.append(text)

    def handle_endtag(self, tag):
        if tag != "a" or not self.href:
            return
        url = urlsplit(self.href)
        if url.hostname == urlsplit(self.source).hostname and url.scheme == "https" and url.path.lower().endswith(".pdf"):
            pattern = r"Fischereirevier Nr\.\s*(\d+)\b" if self.source == AG else r"\s*(\d+)\b"
            label = re.match(pattern, "".join(self.words))
            filename = re.search(r"/Pacht_(\d+)[_.]", url.path, re.I) if self.source == SG else None
            if label and filename and label[1] != filename[1]:
                raise ValueError(f"Conflicting official district numbers: {url.path}")
            identifier = label or filename
            if identifier:
                key = identifier[1]
                if key in self.cards and self.cards[key] != url.path:
                    raise ValueError(f"Duplicate district: {key}")
                self.cards[key] = url.path
        self.href = None


def lease_pages(pdf):
    pages = {}
    with pdfplumber.open(BytesIO(pdf)) as document:
        for page in document.pages:
            words = page.extract_words()
            for i, word in enumerate(words[:-1]):
                # This edition's district-number column starts at PDF x=134.
                # A wrapped description for district 359 starts with "120 m".
                number = word["text"]
                if (133 < word["x0"] < 135 and word["top"] > (210 if page.page_number == 1 else 115)
                        and re.fullmatch(r"\d{1,3}", number) and words[i+1]["text"] != "m"):
                    pages.setdefault(number, page.page_number)
    return pages


def read(url, local):
    if local:
        return Path(local).read_bytes()
    with urlopen(url, timeout=30) as response:
        return response.read()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--zh-pdf")
    parser.add_argument("--sg-html")
    parser.add_argument("--ag-html")
    args = parser.parse_args()
    links = CardLinks(SG)
    links.feed(read(SG, args.sg_html).decode("utf-8"))
    aargau = CardLinks(AG)
    aargau.feed(read(AG, args.ag_html).decode("utf-8"))
    pages = lease_pages(read(ZH, args.zh_pdf))
    if len(links.cards) < 200 or len(pages) < 180 or "120" in pages or len(aargau.cards) < 100:
        raise ValueError("Unexpected register layout; check the current official records.")
    data = {"AG": aargau.cards, "ZH": pages, "SG": links.cards}
    output = "/* Official register links. Generated by tools/build_rights_registers.py. */\n"
    output += "const FishRegisters=" + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
    output += 'if(typeof module!=="undefined"&&module.exports)module.exports=FishRegisters;\n'
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"{len(aargau.cards)} Aargau, {len(pages)} Zurich, {len(links.cards)} St. Gallen")
